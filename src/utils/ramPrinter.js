/**
 * Renders HTML into iframe, waits for all images to complete loading, then fires print
 */
function renderHtmlAndPrint(iframe, htmlContent, onAttachListener, onComplete) {
  const doc = iframe.contentDocument || iframe.contentWindow.document;
  doc.open();
  doc.write(htmlContent);
  doc.close();

  if (typeof onAttachListener === 'function') {
    onAttachListener();
  }

  let printDispatched = false;
  let safetyTimeout = null;

  const executePrint = () => {
    if (printDispatched) return;
    printDispatched = true;
    if (safetyTimeout) clearTimeout(safetyTimeout);

    setTimeout(() => {
      try {
        if (iframe.contentWindow) {
          iframe.contentWindow.focus();
          iframe.contentWindow.print();
        }
        // Immediately release the spooling lock & notify UI that spooling succeeded
        setTimeout(() => {
          if (typeof onComplete === 'function') {
            onComplete();
          }
        }, 400);
      } catch (e) {
        console.error('[NullPin RAM Print] Error calling contentWindow.print():', e);
        if (typeof onComplete === 'function') {
          onComplete();
        }
      }
    }, 250);
  };

  const images = doc.querySelectorAll('img');
  if (images.length === 0) {
    executePrint();
    return;
  }

  let loadedCount = 0;
  const onImgLoad = () => {
    loadedCount++;
    if (loadedCount >= images.length) {
      executePrint();
    }
  };

  images.forEach((img) => {
    if (img.complete) {
      onImgLoad();
    } else {
      img.onload = onImgLoad;
      img.onerror = onImgLoad;
    }
  });

  // Fallback timeout in case image loading stalls (only if not already printed)
  safetyTimeout = setTimeout(() => {
    if (!printDispatched) {
      executePrint();
    }
  }, 1000);
}

