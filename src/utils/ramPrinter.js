function escapeHtml(str) {
  if (!str) return '';
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

async function extractDocxXml(buffer) {
  try {
    const view = new DataView(buffer);
    let eocd = -1;
    for (let i = buffer.byteLength - 22; i >= Math.max(0, buffer.byteLength - 65557); i--) {
      if (view.getUint32(i, true) === 0x06054b50) { eocd = i; break; }
    }
    if (eocd === -1) return null;
    const cdOffset = view.getUint32(eocd + 16, true);
    const cdCount = view.getUint16(eocd + 10, true);
    let offset = cdOffset;
    let docEntry = null;
    for (let i = 0; i < cdCount && offset + 46 <= buffer.byteLength; i++) {
      if (view.getUint32(offset, true) !== 0x02014b50) break;
      const method = view.getUint16(offset + 10, true);
      const compSize = view.getUint32(offset + 20, true);
      const nameLen = view.getUint16(offset + 28, true);
      const extraLen = view.getUint16(offset + 30, true);
      const commentLen = view.getUint16(offset + 32, true);
      const localOffset = view.getUint32(offset + 42, true);
      const name = new TextDecoder().decode(new Uint8Array(buffer, offset + 46, nameLen));
      if (name === 'word/document.xml') {
        docEntry = { method, compSize, localOffset };
        break;
      }
      offset += 46 + nameLen + extraLen + commentLen;
    }
    if (!docEntry) return null;
    const localNameLen = view.getUint16(docEntry.localOffset + 26, true);
    const localExtraLen = view.getUint16(docEntry.localOffset + 28, true);
    const dataStart = docEntry.localOffset + 30 + localNameLen + localExtraLen;
    const compressed = new Uint8Array(buffer, dataStart, docEntry.compSize);
    
    if (docEntry.method === 0) {
      return new TextDecoder().decode(compressed);
    }
    const ds = new DecompressionStream('deflate-raw');
    const writer = ds.writable.getWriter();
    writer.write(compressed);
    writer.close();
    const reader = ds.readable.getReader();
    const chunks = [];
    while (true) {
      const { done, value } = await reader.read();
      if (done) break;
      chunks.push(value);
    }
    const total = chunks.reduce((a, b) => a + b.length, 0);
    const out = new Uint8Array(total);
    let pos = 0;
    for (const c of chunks) { out.set(c, pos); pos += c.length; }
    return new TextDecoder().decode(out);
  } catch (err) {
    console.warn('[NullPin RAM Print] Docx XML extraction error:', err);
    return null;
  }
}

function parseDocxXml(xmlStr) {
  try {
    const parser = new DOMParser();
    const doc = parser.parseFromString(xmlStr, 'application/xml');
    const paragraphs = doc.getElementsByTagName('w:p');
    let html = '';
    for (let i = 0; i < paragraphs.length; i++) {
      const p = paragraphs[i];
      const runs = p.getElementsByTagName('w:r');
      let pContent = '';
      for (let j = 0; j < runs.length; j++) {
        const r = runs[j];
        const isBold = r.getElementsByTagName('w:b').length > 0;
        const isItalic = r.getElementsByTagName('w:i').length > 0;
        const textNodes = r.getElementsByTagName('w:t');
        let rText = '';
        for (let k = 0; k < textNodes.length; k++) {
          rText += textNodes[k].textContent || '';
        }
        if (!rText) continue;
        let formatted = escapeHtml(rText);
        if (isBold) formatted = `<strong>${formatted}</strong>`;
        if (isItalic) formatted = `<em>${formatted}</em>`;
        pContent += formatted;
      }
      if (pContent.trim()) {
        html += `<p style="margin-bottom: 12px; font-size: 11pt; line-height: 1.6; color: #1e293b;">${pContent}</p>`;
      } else {
        html += `<div style="height: 10px;"></div>`;
      }
    }
    return html;
  } catch (e) {
    return null;
  }
}

// Module-level execution lock to strictly prevent duplicate print triggers
let isGlobalPrintLocked = false;

// Reliable mobile environment detection
export const isMobile = typeof navigator !== 'undefined' && /Android|iPhone|iPad|iPod/i.test(navigator.userAgent);

// In-memory cache for remote URLs converted to same-origin Blob URLs (avoids repeat downloads)
const sameOriginBlobCache = new Map();

/**
 * Resolves any remote or cross-origin URL into a clean same-origin Blob URL in browser memory.
 * Bypasses CORS print blocks and provides instant printing without re-fetching.
 */
export async function ensureSameOriginBlobUrl(url, mimeType = 'application/pdf') {
  if (!url) return null;
  // If already a local Blob URL, strip any existing hash or query
  if (url.startsWith('blob:')) {
    return url.split('#')[0];
  }
  if (sameOriginBlobCache.has(url)) {
    return sameOriginBlobCache.get(url);
  }

  try {
    const res = await fetch(url);
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const buffer = await res.arrayBuffer();
    const type = mimeType || res.headers.get('content-type') || 'application/pdf';
    const blob = new Blob([buffer], { type });
    const localBlobUrl = URL.createObjectURL(blob);
    sameOriginBlobCache.set(url, localBlobUrl);
    return localBlobUrl;
  } catch (err) {
    console.warn('[NullPin RAM Print] Remote blob fetch error:', err);
    return url.split('#')[0];
  }
}

// =========================================================================
// PRE-WARMED PRINT IFRAME POOL FOR ZERO-LATENCY CHROMIUM PREVIEWS
// Pre-mounts iframes in DOM on PIN unlock so Chrome PDFium parses 30+ pages
// BEFORE the user clicks 'Print'.
// =========================================================================

// Registry of pre-warmed iframe instances: Map<fileKey, { iframe, isLoaded, blobUrl, type, timestamp }>
const prewarmedFrames = new Map();
// In-flight prewarm promises map to deduplicate concurrent requests
const inFlightPrewarms = new Map();
// Cap concurrent DOM iframe instances to MAX 2 to prevent Chromium CPU & process choke
const MAX_PREWARMED_IFRAMES = 2;

function evictExcessPrewarmedFrames(excludeKey = null) {
  while (prewarmedFrames.size >= MAX_PREWARMED_IFRAMES) {
    let oldestKey = null;
    let oldestTime = Infinity;
    for (const [key, rec] of prewarmedFrames.entries()) {
      if (key === excludeKey) continue;
      const t = rec.timestamp || 0;
      if (t < oldestTime) {
        oldestTime = t;
        oldestKey = key;
      }
    }
    if (!oldestKey) break;
    const rec = prewarmedFrames.get(oldestKey);
    try {
      if (rec?.iframe && rec.iframe.parentNode) {
        rec.iframe.parentNode.removeChild(rec.iframe);
      }
    } catch (e) {}
    prewarmedFrames.delete(oldestKey);
  }
}

// Registry of active focus polling intervals, fallback timers, and watchdog timeouts
const activePrinterTimers = new Set();

export function registerPrinterInterval(fn, ms) {
  const id = setInterval(fn, ms);
  const clear = () => clearInterval(id);
  activePrinterTimers.add(clear);
  return {
    id,
    clear: () => {
      clear();
      activePrinterTimers.delete(clear);
    }
  };
}

export function registerPrinterTimeout(fn, ms) {
  let id = null;
  const clear = () => clearTimeout(id);
  id = setTimeout(() => {
    activePrinterTimers.delete(clear);
    fn();
  }, ms);
  activePrinterTimers.add(clear);
  return {
    id,
    clear: () => {
      clear();
      activePrinterTimers.delete(clear);
    }
  };
}

/**
 * Destroys all pre-warmed iframes from the DOM and clears the cache
 */
export function cleanupPrewarmedFrames() {
  inFlightPrewarms.clear();

  // Clear all registered active intervals & timeouts
  for (const clearFn of activePrinterTimers) {
    try { clearFn(); } catch (e) {}
  }
  activePrinterTimers.clear();
  isGlobalPrintLocked = false;

  for (const [, record] of prewarmedFrames.entries()) {
    try {
      if (record?.iframe && record.iframe.parentNode) {
        record.iframe.parentNode.removeChild(record.iframe);
      }
    } catch (e) {}
  }
  prewarmedFrames.clear();
}

